"""Build the data-driven parts of the report from the running stack.

Run from the repository root while the stack is up:
    python3 report/tools/make_numbers.py [--last-day YYYY-MM-DD] [--prom-time UNIX_SECONDS]

--last-day   only use batch results up to this simulated day
--prom-time  evaluate Prometheus queries at this moment (for example just before a failure drill)

It reads PostgreSQL (through `docker compose exec`) and Prometheus (HTTP) and
writes LaTeX files into report/sections/:
    numbers.tex            \\newcommand macros with measured values
    gen_daily_table.tex    batch results per simulated day
    gen_recon_table.tex    speed layer versus batch layer, and data quality
    gen_trend_plot.tex     pgfplots chart of daily net profit per problem vehicle
    gen_perf_table.tex     latency, batch duration and memory
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import subprocess
import sys
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "report" / "sections"
PROM = "http://localhost:9090/api/v1/query"
SPECIAL = ["V007", "V013", "V026"]


def sql(query: str) -> list[dict]:
    cmd = ["docker", "compose", "exec", "-T", "postgres", "psql", "-U", "fleet", "-d", "fleet", "-c",
           f"COPY ({query}) TO STDOUT WITH CSV HEADER"]
    out = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return list(csv.DictReader(io.StringIO(out)))


PROM_TIME: float | None = None


def prom(expr: str) -> list[dict]:
    params = {"query": expr}
    if PROM_TIME:
        params["time"] = f"{PROM_TIME:.0f}"
    url = PROM + "?" + urllib.parse.urlencode(params)
    with urllib.request.urlopen(url, timeout=10) as resp:
        return json.load(resp)["data"]["result"]


def prom_value(expr: str, default: float = 0.0) -> float:
    result = prom(expr)
    return float(result[0]["value"][1]) if result else default


def money(v) -> str:
    return f"{float(v):,.0f}"


def day_label(d: str) -> str:
    x = date.fromisoformat(d)
    return f"{x.day} {x.strftime('%b')}"


def pct(v, digits=1) -> str:
    return "-" if v in (None, "") else f"{float(v):.{digits}f}"


def main() -> int:
    global PROM_TIME
    parser = argparse.ArgumentParser()
    parser.add_argument("--last-day", default="9999-12-31")
    parser.add_argument("--prom-time", type=float, default=None)
    args = parser.parse_args()
    PROM_TIME = args.prom_time
    last = args.last_day
    days = sql(f"SELECT * FROM batch.daily_summary WHERE sim_date <= '{last}' ORDER BY sim_date")
    if not days:
        print("no batch results yet")
        return 1
    recon = sql(f"SELECT * FROM ops.layer_reconciliation WHERE sim_date <= '{last}' ORDER BY sim_date, metric")
    runs = sql(f"SELECT sim_date, details FROM ops.pipeline_runs WHERE stage = 'batch_layer' AND status = 'success' "
               f"AND sim_date <= '{last}' ORDER BY sim_date")
    prof = sql(f"SELECT sim_date, vehicle_id, net_profit_lkr, status, becoming_unprofitable "
               f"FROM batch.vehicle_profitability WHERE sim_date <= '{last}' ORDER BY sim_date, vehicle_id")
    until = f"to_timestamp({PROM_TIME:.0f})" if PROM_TIME else "now()"
    clock = sql(f"SELECT round(extract(epoch FROM {until} - real_start) / 60) AS minutes, sim_now FROM serving.v_sim_clock")[0]

    # ---------------------------------------------------------------- macros
    full = [d for d in days if d["sim_date"] != days[0]["sim_date"]] or days  # day 1 is only 18 hours
    events_per_day = sum(int(d["events_total"]) for d in full) / len(full)
    late_per_day = sum(int(d["late_events"]) for d in full) / len(full)
    trips_per_day = sum(int(d["trips"]) for d in full) / len(full)
    durations = [json.loads(r["details"]).get("duration_s", 0) for r in runs]
    latency_avg = prom_value('avg_over_time(speed_e2e_latency_seconds{query="vehicle_state"}[1h])')
    macros = {
        "NumDays": str(len(days)),
        "RunMinutes": str(int(float(clock["minutes"]))),
        "LatencyAvg": f"{latency_avg:.1f}",
        "EventsPerDay": f"{round(events_per_day, -2):,.0f}",
        "LateEventsPerDay": f"{late_per_day:,.0f}",
        "TripsPerDay": f"{trips_per_day:,.0f}",
        "BatchSecondsAvg": f"{sum(durations) / len(durations):.0f}" if durations else "0",
        "ReportDay": day_label(days[-1]["sim_date"]),
        "LastDay": days[-1]["sim_date"],
    }
    lines = ["% generated by report/tools/make_numbers.py - do not edit by hand"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n")

    # ----------------------------------------------------------- daily table
    rows = []
    for d in days:
        cost = float(d["fuel_cost_lkr"]) + float(d["maintenance_cost_lkr"])
        rows.append(
            f"{day_label(d['sim_date'])} & {d['trips']} & {money(d['revenue_lkr'])} & {money(cost)} & "
            f"{money(d['net_profit_lkr'])} & {pct(d['fleet_utilization_pct'])} & {d['unprofitable_vehicles']} & "
            f"{d['at_risk_vehicles']} & {d['becoming_unprofitable_vehicles']} \\\\"
        )
    (OUT / "gen_daily_table.tex").write_text(
        "\\begin{table}[!htb]\n\\centering\\small\n"
        "\\caption{Exact daily results from the batch layer (money in LKR). Day 1 is 18 hours long.}\n"
        "\\label{tab:daily}\n"
        "\\begin{tabular}{@{}lrrrrrrrr@{}}\n\\toprule\n"
        "\\textbf{Day} & \\textbf{Trips} & \\textbf{Fares} & \\textbf{Fuel + maint.} & \\textbf{Net profit} & "
        "\\textbf{Util. \\%} & \\textbf{Unprof.} & \\textbf{At risk} & \\textbf{Becoming} \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )

    # ----------------------------------------------------------- recon table
    # one row per measure (lowest, average and highest day) keeps the table short
    full_dates = {d["sim_date"] for d in full}
    by_metric: dict[str, list[dict]] = {}
    for r in recon:
        if r["sim_date"] in full_dates:
            by_metric.setdefault(r["metric"], []).append(r)

    def spread(values: list[float], fmt: str, avg_fmt: str | None = None) -> str:
        if not values:
            return "- & - & -"
        avg = (avg_fmt or fmt).format(sum(values) / len(values))
        return f"{fmt.format(min(values))} & {avg} & {fmt.format(max(values))}"

    missed = [float(r["batch_value"]) - float(r["speed_value"]) for r in by_metric.get("trips_completed", [])]
    measures = [
        ("Trips missed by the speed layer", spread(missed, "{:.0f}", "{:.1f}")),
        ("Fares missed by the speed layer (\\% of batch fares)",
         spread([float(r["diff_pct"]) for r in by_metric.get("earnings_lkr", [])], "{:.2f}")),
        ("Pings missed by the speed layer (\\% of batch pings)",
         spread([float(r["diff_pct"]) for r in by_metric.get("pings", [])], "{:.2f}")),
        ("Late events (more than 10 simulated minutes)", spread([float(d["late_events"]) for d in full], "{:,.0f}")),
        ("Repeated events removed", spread([float(d["duplicates_removed"]) for d in full], "{:,.0f}")),
        ("Invalid events removed", spread([float(d["events_invalid"]) for d in full], "{:,.0f}")),
        ("Bad cost rows put in quarantine", spread([float(d["expense_rows_quarantined"]) for d in full], "{:.0f}", "{:.1f}")),
    ]
    (OUT / "gen_recon_table.tex").write_text(
        "\\begin{table}[!htb]\n\\centering\\small\n"
        f"\\caption{{Speed layer compared with the batch layer, and what the batch layer cleaned, per day "
        f"(days 2 to {len(days)}, lowest, average and highest day).}}\n"
        "\\label{tab:recon}\n"
        "\\begin{tabularx}{\\textwidth}{@{}L rrr@{}}\n\\toprule\n"
        "\\textbf{Measure per day} & \\textbf{Lowest} & \\textbf{Average} & \\textbf{Highest} \\\\\n\\midrule\n"
        + "\n".join(f"{name} & {values} \\\\" for name, values in measures)
        + "\n\\bottomrule\n\\end{tabularx}\n\\end{table}\n"
    )

    # ------------------------------------------------------------ trend plot
    day_list = [d["sim_date"] for d in days]
    net: dict[str, dict[str, float]] = {}
    for p in prof:
        net.setdefault(p["vehicle_id"], {})[p["sim_date"]] = float(p["net_profit_lkr"])
    others = {}
    for day in day_list:
        values = [v[day] for vid, v in net.items() if vid not in SPECIAL and day in v]
        others[day] = sum(values) / len(values) if values else 0.0
    styles = {"V007": "red, mark=square*", "V013": "orange, mark=triangle*", "V026": "blue, mark=diamond*"}
    legend = {"V007": "V007 (degrading)", "V013": "V013 (high maintenance)", "V026": "V026 (fuel anomaly)"}
    plots = []
    for vid in SPECIAL:
        coords = " ".join(f"({i + 1},{net.get(vid, {}).get(day, 0):.0f})" for i, day in enumerate(day_list))
        plots.append(f"\\addplot[{styles[vid]}, thick] coordinates {{{coords}}};\n\\addlegendentry{{{legend[vid]}}}")
    coords = " ".join(f"({i + 1},{others[day]:.0f})" for i, day in enumerate(day_list))
    plots.append(f"\\addplot[black!60, dashed, thick, mark=*] coordinates {{{coords}}};\n"
                 f"\\addlegendentry{{average of other vehicles}}")
    ticks = ",".join(str(i + 1) for i in range(len(day_list)))
    labels = ",".join(str(date.fromisoformat(d).day) for d in day_list)
    (OUT / "gen_trend_plot.tex").write_text(
        "\\begin{tikzpicture}\n\\begin{axis}[width=0.92\\textwidth, height=5.6cm, font=\\sffamily\\footnotesize,\n"
        f"  xtick={{{ticks}}}, xticklabels={{{labels}}}, xmin=0.7, xmax={len(day_list) + 0.3},\n"
        "  xlabel={simulated day in September 2026}, ylabel={net profit (LKR)}, ymajorgrids, grid style={black!12},\n"
        "  yticklabel style={/pgf/number format/fixed, /pgf/number format/1000 sep={,}},\n"
        "  scaled y ticks=false, legend style={font=\\sffamily\\scriptsize, at={(0.5,-0.3)}, anchor=north,\n"
        "  legend columns=2, draw=none}]\n"
        "\\addplot[black!40, thin, forget plot] coordinates {(0.7,0) " + f"({len(day_list) + 0.3},0)" + "};\n"
        + "\n".join(plots) + "\n\\end{axis}\n\\end{tikzpicture}\n"
    )

    # ------------------------------------------------------------ perf table
    lat_vs = prom_value('avg_over_time(speed_e2e_latency_seconds{query="vehicle_state"}[1h])')
    lat_zh = prom_value('avg_over_time(speed_e2e_latency_seconds{query="zone_hourly"}[1h])')
    lat_max = prom_value('max_over_time(speed_e2e_max_latency_seconds{query="vehicle_state"}[1h])')
    batch_vs = prom_value('avg_over_time(speed_query_batch_duration_seconds{query="vehicle_state"}[1h])')
    batch_zh = prom_value('avg_over_time(speed_query_batch_duration_seconds{query="zone_hourly"}[1h])')
    rate = prom_value("sum(rate(producer_events_sent_total[1h]))")
    lag = prom_value("max(max_over_time(speed_kafka_offsets_behind_latest[1h]))")
    delivery = prom_value("histogram_quantile(0.95, sum by (le) (rate(producer_delivery_latency_seconds_bucket[1h])))")
    steps: dict[str, list[float]] = {}
    for r in runs:
        for k, v in json.loads(r["details"]).get("steps_s", {}).items():
            steps.setdefault(k, []).append(v)
    order = ["spark_start", "validate_expenses", "clean_telemetry", "join_and_profitability",
             "write_curated_parquet", "publish_postgres"]
    keys = [k for k in order if k in steps] + [k for k in steps if k not in order]
    step_text = ", ".join(f"{k.replace('_', ' ')} {sum(steps[k]) / len(steps[k]):.0f}\\,s" for k in keys)
    mem = subprocess.run(["docker", "stats", "--no-stream", "--format", "{{.Name}}|{{.MemUsage}}"],
                         capture_output=True, text=True, check=True).stdout
    mem_rows = []
    for line in mem.strip().splitlines():
        name, usage = line.split("|")
        if name.startswith("fleetpulse-"):
            mem_rows.append((name.replace("fleetpulse-", "").rsplit("-", 1)[0], usage.split("/")[0].strip()))
    mem_rows.sort()

    def mib(usage: str) -> float:
        for unit, factor in (("GiB", 1024.0), ("MiB", 1.0), ("KiB", 1 / 1024.0)):
            if usage.endswith(unit):
                return float(usage[: -len(unit)]) * factor
        return float(usage.rstrip("B")) / 1024 / 1024

    total = sum(mib(u) for _, u in mem_rows)
    mem_text = ", ".join(f"{n} {mib(u):.0f}" for n, u in mem_rows) + f" (MiB, total {total / 1024:.1f}\\,GiB)"
    perf = [
        ("Events per second into Kafka (average)", f"{rate:.1f}"),
        ("Producer delivery latency, 95th percentile", f"{delivery * 1000:.0f}\\,ms"),
        ("End-to-end latency Kafka to PostgreSQL, vehicle state (average)", f"{lat_vs:.1f}\\,s"),
        ("End-to-end latency, oldest record in a vehicle-state batch (maximum)", f"{lat_max:.1f}\\,s"),
        ("End-to-end latency, zone by hour windows (average)", f"{lat_zh:.1f}\\,s"),
        ("Micro-batch duration: vehicle state and zone by hour (average)", f"{batch_vs:.1f}\\,s and {batch_zh:.1f}\\,s"),
        ("Largest Kafka lag of any streaming query", f"{lag:.0f} offsets"),
        ("Spark batch job for one simulated day (average)", f"{macros['BatchSecondsAvg']}\\,s"),
    ]
    (OUT / "gen_perf_table.tex").write_text(
        "\\begin{table}[!htb]\n\\centering\\small\n\\caption{Speed and resource use during the run.}\n\\label{tab:perf}\n"
        "\\begin{tabularx}{\\textwidth}{@{}L r@{}}\n\\toprule\n\\textbf{Measure} & \\textbf{Value} \\\\\n\\midrule\n"
        + "\n".join(f"{a} & {b} \\\\" for a, b in perf)
        + "\n\\midrule\n\\multicolumn{2}{@{}p{\\dimexpr\\textwidth\\relax}@{}}{\\raggedright\\textbf{Batch job steps "
          "(average):} " + step_text + "} \\\\\n"
        "\\multicolumn{2}{@{}p{\\dimexpr\\textwidth\\relax}@{}}{\\raggedright\\textbf{Memory per container:} "
        + mem_text + "} \\\\\n\\bottomrule\n\\end{tabularx}\n\\end{table}\n"
    )
    print(json.dumps(macros, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
